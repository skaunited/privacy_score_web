#!/usr/bin/env node
/** Generate Plesk server-context redirects from the application's route registry. */
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { SITE_ORIGIN, PAGE_PATHS, LEGACY_REDIRECTS } from '../src/i18n/routes.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = path.join(root, 'deploy/redirects.nginx.conf');
const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const routes = new Set(Object.values(PAGE_PATHS).flatMap(Object.values));
for (const language of ['en', 'fr']) {
  for (const file of (await readdir(path.join(root, 'src/content/blog', language))).filter((name) => name.endsWith('.md')).sort()) {
    const text = await readFile(path.join(root, 'src/content/blog', language, file), 'utf8');
    const frontmatter = text.split('---')[1] ?? '';
    if (/^draft:\s*true\s*$/m.test(frontmatter) || /^status:\s*["']?draft["']?\s*$/m.test(frontmatter)) continue;
    const publication = frontmatter.match(/^publishedAt:\s*["']?([^\s"']+)["']?\s*$/m)?.[1];
    if (publication && new Date(publication) > new Date()) continue;
    const slug = frontmatter.match(/^slug:\s*["']?([^\s"']+)["']?\s*$/m)?.[1];
    if (!slug || !/^[a-z0-9-]+$/.test(slug)) throw new Error(`Invalid blog slug in ${file}`);
    routes.add(`${language === 'fr' ? '/fr' : ''}/blog/${slug}/`);
  }
}
const entries = Object.entries(LEGACY_REDIRECTS).sort(([a], [b]) => a.localeCompare(b));
for (const [from, to] of entries) {
  if (from === to || !routes.has(to) || Object.hasOwn(LEGACY_REDIRECTS, to)) {
    throw new Error(`Redirect must point directly to a published canonical route: ${from} -> ${to}`);
  }
}
const lines = [
  '# GENERATED by node scripts/generate-redirects.mjs; do not edit by hand.',
  '# Merge in Plesk > Apache & nginx Settings > Additional nginx directives.',
  '# Server context only. These return directives add no duplicate locations.',
  '# $request_uri is the original request, even after an internal index redirect.',
  '# Keep these permanent redirects after the migration. Query strings survive.',
  '',
  '# Historical paths, including slashless and explicit index.html variants.',
];
for (const [from, to] of entries) {
  const source = escape(from.replace(/\/$/, ''));
  lines.push(`if ($request_uri ~ "^${source}(?:/index\\.html|/)?(?:\\?|$)") {`, `    return 301 ${SITE_ORIGIN}${to}$is_args$args;`, '}');
}
lines.push('', '# Canonical published routes: /page and /page/index.html -> /page/.');
for (const route of [...routes].sort()) {
  const expression = route === '/' ? '^/index\\.html(?:\\?|$)' : `^${escape(route.slice(0, -1))}(?:/index\\.html)?(?:\\?|$)`;
  lines.push(`if ($request_uri ~ "${expression}") {`, `    return 301 ${SITE_ORIGIN}${route}$is_args$args;`, '}');
}
const output = `${lines.join('\n')}\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('Redirect config is stale. Run node scripts/generate-redirects.mjs.');
    process.exitCode = 1;
  } else console.log(`Redirect config current: ${entries.length} legacy paths, ${routes.size} canonical routes.`);
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, output);
  console.log(`Generated deploy/redirects.nginx.conf: ${entries.length} legacy paths, ${routes.size} canonical routes.`);
}
